package io.openems.edge.mqtt.generic.timeofusetariff;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Time-Of-Use Tariff MQTT", //
		description = "Dynamic electricity prices from a JSON array published on an MQTT topic (via Bridge.Mqtt). "
				+ "Prices are used as-is in the global OpenEMS currency (set Core.Meta currency accordingly).")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "timeOfUseTariff0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "MQTT Bridge-ID", description = "ID of the Bridge.Mqtt component")
	String mqttBridge_id() default "mqtt0";

	@AttributeDefinition(name = "Topic", description = "Topic with the JSON price list")
	String topic() default "ekz/ems/tariffs/intervals";

	@AttributeDefinition(name = "Array field", description = "Name of the JSON array holding the intervals; "
			+ "empty if the payload itself is the array")
	String arrayField() default "intervals";

	@AttributeDefinition(name = "Start timestamp field", description = "ISO-8601 timestamp with offset, "
			+ "e.g. 2026-11-11T00:15:00+01:00")
	String startField() default "start_timestamp";

	@AttributeDefinition(name = "Price field", description = "Price per kWh field")
	String priceField() default "chf_per_kwh_sum";

	@AttributeDefinition(name = "Price scale", description = "Factor to convert the price to price per MWh "
			+ "(OpenEMS unit). 1000 for a price per kWh.")
	double priceScale() default 1000.0;

	@AttributeDefinition(name = "MQTT Bridge target filter", description = "This is auto-generated by 'MQTT Bridge-ID'.")
	String mqttBridge_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Time-Of-Use Tariff MQTT [{id}]";

}
