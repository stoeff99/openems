package io.openems.edge.mqtt.generic.ess;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "ESS MQTT (read-only)", //
		description = "Battery energy storage system that reads its values from MQTT topics (via Bridge.Mqtt). "
				+ "Read-only: OpenEMS does not control the battery.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "ess0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "MQTT Bridge-ID", description = "ID of the Bridge.Mqtt component")
	String mqttBridge_id() default "mqtt0";

	@AttributeDefinition(name = "Topic: State of Charge [%]", description = "e.g. Cerbo/N/<id>/system/0/Dc/Battery/Soc")
	String socTopic() default "";

	@AttributeDefinition(name = "Topic: Active Power [W]", description = "e.g. Cerbo/N/<id>/system/0/Dc/Battery/Power")
	String activePowerTopic() default "";

	@AttributeDefinition(name = "Invert Power", description = "OpenEMS: + = discharge, - = charge. "
			+ "Victron reports + = charge, so keep this enabled for a Cerbo GX.")
	boolean invertPower() default true;

	@AttributeDefinition(name = "Power Scale", description = "Factor to convert the payload to Watt (e.g. 1000 for kW)")
	double powerScale() default 1.0;

	@AttributeDefinition(name = "Capacity [Wh]", description = "Usable battery capacity")
	int capacity() default 10000;

	@AttributeDefinition(name = "Max Apparent Power [VA]", description = "Maximum inverter power")
	int maxApparentPower() default 5000;

	@AttributeDefinition(name = "Topic: Charged Energy", description = "Optional cumulative counter (see Energy Scale), "
			+ "e.g. .../battery/512/History/ChargedEnergy. If empty, calculated from power.")
	String chargeEnergyTopic() default "";

	@AttributeDefinition(name = "Topic: Discharged Energy", description = "Optional cumulative counter (see Energy Scale), "
			+ "e.g. .../battery/512/History/DischargedEnergy. If empty, calculated from power.")
	String dischargeEnergyTopic() default "";

	@AttributeDefinition(name = "Energy Scale", description = "Factor to convert energy payloads to Wh (1000 for kWh)")
	double energyScale() default 1000.0;

	@AttributeDefinition(name = "Topic: Min Cell Voltage [V]", description = "Optional")
	String minCellVoltageTopic() default "";

	@AttributeDefinition(name = "Topic: Max Cell Voltage [V]", description = "Optional")
	String maxCellVoltageTopic() default "";

	@AttributeDefinition(name = "Topic: Battery Temperature [°C]", description = "Optional; used for min and max cell temperature")
	String temperatureTopic() default "";

	@AttributeDefinition(name = "JSON Path", description = "Optional dotted path for JSON payloads. "
			+ "Plain numbers and Victron {\"value\": x} payloads work without it.")
	String jsonPath() default "";

	@AttributeDefinition(name = "Timeout [s]", description = "Power is set to 'undefined' if no message arrives "
			+ "within this time. 0 = disabled.")
	int timeoutSeconds() default 120;

	@AttributeDefinition(name = "MQTT Bridge target filter", description = "This is auto-generated by 'MQTT Bridge-ID'.")
	String mqttBridge_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "ESS MQTT [{id}]";

}
