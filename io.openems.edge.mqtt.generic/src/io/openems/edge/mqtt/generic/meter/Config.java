package io.openems.edge.mqtt.generic.meter;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

import io.openems.common.types.MeterType;

@ObjectClassDefinition(//
		name = "Meter MQTT", //
		description = "Generic electricity meter that reads its values from MQTT topics (via Bridge.Mqtt). "
				+ "Use it for Grid, PV production or consumption.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "meter0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Meter-Type", description = "GRID (+ = buy from grid, - = feed-in), "
			+ "PRODUCTION (+ = producing) or CONSUMPTION_METERED (+ = consuming)")
	MeterType type() default MeterType.GRID;

	@AttributeDefinition(name = "MQTT Bridge-ID", description = "ID of the Bridge.Mqtt component")
	String mqttBridge_id() default "mqtt0";

	@AttributeDefinition(name = "Topic: Active Power [W]", description = "Topic for total active power. "
			+ "Leave empty to calculate the total from the L1/L2/L3 topics.")
	String activePowerTopic() default "";

	@AttributeDefinition(name = "Topic: Active Power L1 [W]", description = "Optional")
	String activePowerL1Topic() default "";

	@AttributeDefinition(name = "Topic: Active Power L2 [W]", description = "Optional")
	String activePowerL2Topic() default "";

	@AttributeDefinition(name = "Topic: Active Power L3 [W]", description = "Optional")
	String activePowerL3Topic() default "";

	@AttributeDefinition(name = "Topic: Production/Export Energy", description = "Optional cumulative energy counter "
			+ "(see Energy Scale). If empty, energy is calculated from power.")
	String productionEnergyTopic() default "";

	@AttributeDefinition(name = "Topic: Consumption/Import Energy", description = "Optional cumulative energy counter "
			+ "(see Energy Scale). If empty, energy is calculated from power.")
	String consumptionEnergyTopic() default "";

	@AttributeDefinition(name = "JSON Path", description = "Optional dotted path for JSON payloads (e.g. 'data.power'). "
			+ "Plain numbers and Victron {\"value\": x} payloads work without it.")
	String jsonPath() default "";

	@AttributeDefinition(name = "Invert Power", description = "Multiply power values by -1 to match OpenEMS sign convention")
	boolean invert() default false;

	@AttributeDefinition(name = "Power Scale", description = "Factor to convert the payload to Watt (e.g. 1000 for kW)")
	double powerScale() default 1.0;

	@AttributeDefinition(name = "Energy Scale", description = "Factor to convert energy payloads to Wh (1000 for kWh)")
	double energyScale() default 1000.0;

	@AttributeDefinition(name = "Timeout [s]", description = "Power is set to 'undefined' if no message arrives "
			+ "within this time. 0 = disabled.")
	int timeoutSeconds() default 120;

	@AttributeDefinition(name = "MQTT Bridge target filter", description = "This is auto-generated by 'MQTT Bridge-ID'.")
	String mqttBridge_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Meter MQTT [{id}]";

}
