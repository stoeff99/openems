package io.openems.edge.mqtt.generic.predictor;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Predictor MQTT Hourly Forecast", //
		description = "Production forecast from hourly kWh values on MQTT, e.g. a Solcast LoxBerry plugin "
				+ "publishing <prefix>today_hour_HH_kwh and <prefix>tomorrow_hour_HH_kwh.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "predictor0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "MQTT Bridge-ID", description = "ID of the Bridge.Mqtt component")
	String mqttBridge_id() default "mqtt0";

	@AttributeDefinition(name = "Topic prefix", description = "Prefix of the hourly forecast topics")
	String topicPrefix() default "solcast/sum/";

	@AttributeDefinition(name = "Channel-Addresses", description = "Channels this forecast is provided for")
	String[] channelAddresses() default { "_sum/ProductionActivePower" };

	@AttributeDefinition(name = "Time zone", description = "Time zone of the 'hour_HH' values")
	String timeZone() default "Europe/Zurich";

	@AttributeDefinition(name = "Energy scale", description = "Factor to convert one hour of energy into average Watt "
			+ "(1000 for kWh)")
	double energyScale() default 1000.0;

	@AttributeDefinition(name = "MQTT Bridge target filter", description = "This is auto-generated by 'MQTT Bridge-ID'.")
	String mqttBridge_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Predictor MQTT Hourly Forecast [{id}]";

}
